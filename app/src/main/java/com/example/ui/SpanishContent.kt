private fun exactSpanish(text: String, language: AppLanguage): String =
    TranslationCatalog.exact(text, language) ?: text

internal fun localizeLatinAmericanSpanishDynamicContent(text: String): String? =
    localizeSpanishDynamicContent(text, AppLanguage.SPANISH_LATIN_AMERICA)

internal fun localizeSpainSpanishDynamicContent(text: String): String? =
    localizeSpanishDynamicContent(text, AppLanguage.SPANISH_SPAIN)

private fun localizeSpanishDynamicContent(text: String, language: AppLanguage): String? {
    Regex("^([\\p{So}\\p{Sk}\\uFE0F\\u200D]+\\s+)(.+)$").matchEntire(text)?.let {
        TranslationCatalog.exact(it.groupValues[2], language)?.let { translated ->
            return it.groupValues[1] + translated
        }
    }
    Regex("^(\\d+[.)]\\s+)(.+)$").matchEntire(text)?.let {
        TranslationCatalog.exact(it.groupValues[2], language)?.let { translated ->
            return it.groupValues[1] + translated
        }
    }
    Regex("^(\\d+) Bilder geladen — Namen prüfen, dann erstellen\\.$").matchEntire(text)?.let {
        return "${it.groupValues[1]} imágenes cargadas — revisa los nombres y crea el paquete."
    }
    Regex("^(\\d+) Bilder geladen\\.$").matchEntire(text)?.let {
        return "${it.groupValues[1]} imágenes cargadas."
    }
    Regex("^(\\d+) Paare aus (\\d+) Bildern$").matchEntire(text)?.let {
        return "${it.groupValues[1]} pares de ${it.groupValues[2]} imágenes"
    }
    Regex("^Bild (\\d+) von (\\d+)…$").matchEntire(text)?.let {
        return "Imagen ${it.groupValues[1]} de ${it.groupValues[2]}…"
    }
    Regex("^Speichere Bild (\\d+) von (\\d+)…$").matchEntire(text)?.let {
        return "Guardando imagen ${it.groupValues[1]} de ${it.groupValues[2]}…"
    }
    Regex("^Paar (\\d+)$").matchEntire(text)?.let { return "Par ${it.groupValues[1]}" }
    Regex("^Frage (\\d+)$").matchEntire(text)?.let { return "Pregunta ${it.groupValues[1]}" }
    Regex("^Schritt (\\d+)$").matchEntire(text)?.let { return "Paso ${it.groupValues[1]}" }
    Regex("^(\\d+) Paare$").matchEntire(text)?.let { return "${it.groupValues[1]} pares" }
    Regex("^(\\d+) Fragen$").matchEntire(text)?.let { return "${it.groupValues[1]} preguntas" }
    Regex("^(\\d+) Schritt\\(e\\)$").matchEntire(text)?.let { return "${it.groupValues[1]} pasos" }
    Regex("^(\\d+) Paare · (\\d+) Fragen$").matchEntire(text)?.let {
        return "${it.groupValues[1]} pares · ${it.groupValues[2]} preguntas"
    }
    Regex("^(\\d+) Einträge$").matchEntire(text)?.let { return "${it.groupValues[1]} entradas" }
    Regex("^Fertig: (\\d+) Pakete · (\\d+) Bilder · (.+)$").matchEntire(text)?.let {
        return "Listo: ${it.groupValues[1]} paquetes · ${it.groupValues[2]} imágenes · ${it.groupValues[3]}"
    }
    Regex("^🎉 (\\d+) Pakete/Ketten & Bilder erfolgreich eingespielt!$").matchEntire(text)?.let {
        return "🎉 ¡${it.groupValues[1]} paquetes/cadenas e imágenes importados correctamente!"
    }
    Regex("^🎉 '(.+)' angelegt · (\\d+) Paare spielbereit$").matchEntire(text)?.let {
        return "🎉 '${exactSpanish(it.groupValues[1], language)}' creado · ${it.groupValues[2]} pares listos para jugar"
    }
    Regex("^• ([AB]): (.+) \\(Bild: (.+)\\)$").matchEntire(text)?.let {
        return "• ${it.groupValues[1]}: ${exactSpanish(it.groupValues[2], language)} (Imagen: ${it.groupValues[3]})"
    }
    Regex("^([AB]): (.+)$").matchEntire(text)?.let {
        return "${it.groupValues[1]}: ${exactSpanish(it.groupValues[2], language)}"
    }
    Regex("^'(.+)' gelöscht\\.$").matchEntire(text)?.let {
        return "'${exactSpanish(it.groupValues[1], language)}' eliminado."
    }
    Regex("^'(.+)' gespeichert\\.$").matchEntire(text)?.let {
        return "'${exactSpanish(it.groupValues[1], language)}' guardado."
    }
    Regex("^Kategorie '(.+)' gespeichert\\.$").matchEntire(text)?.let {
        return "Categoría '${exactSpanish(it.groupValues[1], language)}' guardada."
    }
    Regex("^Kette '(.+)' gespeichert\\.$").matchEntire(text)?.let {
        return "Cadena '${exactSpanish(it.groupValues[1], language)}' guardada."
    }
    Regex("^Kette '(.+)' gelöscht\\.$").matchEntire(text)?.let {
        return "Cadena '${exactSpanish(it.groupValues[1], language)}' eliminada."
    }
    Regex("^Bild für '(.+)' gesetzt\\.$").matchEntire(text)?.let {
        return "Imagen asignada a '${exactSpanish(it.groupValues[1], language)}'."
    }
    Regex("^Eigenes Bild für '(.+)' entfernt\\.$").matchEntire(text)?.let {
        return "Imagen personalizada eliminada de '${exactSpanish(it.groupValues[1], language)}'."
    }
    Regex("^(.+) „(.+)\" an (.+) gesendet$").matchEntire(text)?.let {
        return "${it.groupValues[1]} “${exactSpanish(it.groupValues[2], language)}” enviado a ${it.groupValues[3]}"
    }
    Regex("^6 Monate im (.+)$").matchEntire(text)?.let {
        return "6 meses en ${exactSpanish(it.groupValues[1], language)}"
    }
    Regex("^1 Jahr lang in (.+)$").matchEntire(text)?.let {
        return "1 año en ${exactSpanish(it.groupValues[1], language)}"
    }
    Regex("^Weil du (.+) gewählt hast …$").matchEntire(text)?.let {
        return "Porque elegiste ${exactSpanish(it.groupValues[1], language)}…"
    }
    Regex("^Verbinde dich mit (.+), um die Antwort zu sehen$").matchEntire(text)?.let {
        return "Conéctate con ${it.groupValues[1]} para ver la respuesta"
    }
    Regex("^Verbinde dich mit (.+)$").matchEntire(text)?.let {
        return "Conéctate con ${it.groupValues[1]}"
    }
    Regex("^Deine Antworten sind gespeichert\\. Sobald (.+) das Paket beendet, werden beide Antworten gemeinsam sichtbar\\.$")
        .matchEntire(text)?.let {
            return "Tus respuestas están guardadas. Cuando ${it.groupValues[1]} termine el paquete, podrán ver ambas respuestas."
        }
    Regex("^Fehler bei der Umformulierung: (.+)$").matchEntire(text)?.let {
        return "Error al reformular: ${it.groupValues[1]}"
    }
    Regex("^Fehler bei der Analyse: (.+)$").matchEntire(text)?.let {
        return "Error durante el análisis: ${it.groupValues[1]}"
    }
    Regex("^Fehler bei der Ideengenerierung: (.+)$").matchEntire(text)?.let {
        return "Error al generar ideas: ${it.groupValues[1]}"
    }
    if (text.contains(" · ")) {
        val translated = text.split(" · ").joinToString(" · ") {
            TranslationCatalog.translate(it, language) ?: it
        }
        if (translated != text) return translated
    }
    return null
}
