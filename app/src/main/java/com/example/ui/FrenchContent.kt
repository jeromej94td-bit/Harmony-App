private fun exactFrench(text: String): String =
    TranslationCatalog.exact(text, AppLanguage.FRENCH) ?: text

internal fun localizeFrenchDynamicContent(text: String): String? {
    Regex("^([\\p{So}\\p{Sk}\\uFE0F\\u200D]+\\s+)(.+)$").matchEntire(text)?.let {
        TranslationCatalog.exact(it.groupValues[2], AppLanguage.FRENCH)?.let { translated -> return it.groupValues[1] + translated }
    }
    Regex("^(\\d+[.)]\\s+)(.+)$").matchEntire(text)?.let {
        TranslationCatalog.exact(it.groupValues[2], AppLanguage.FRENCH)?.let { translated -> return it.groupValues[1] + translated }
    }
    Regex("^(\\d+) Bilder geladen — Namen prüfen, dann erstellen\\.$").matchEntire(text)?.let { return "${it.groupValues[1]} images chargées — vérifie les noms, puis crée le pack." }
    Regex("^(\\d+) Bilder geladen\\.$").matchEntire(text)?.let { return "${it.groupValues[1]} images chargées." }
    Regex("^(\\d+) Paare aus (\\d+) Bildern$").matchEntire(text)?.let { return "${it.groupValues[1]} paires à partir de ${it.groupValues[2]} images" }
    Regex("^Bild (\\d+) von (\\d+)…$").matchEntire(text)?.let { return "Image ${it.groupValues[1]} sur ${it.groupValues[2]}…" }
    Regex("^Speichere Bild (\\d+) von (\\d+)…$").matchEntire(text)?.let { return "Enregistrement de l'image ${it.groupValues[1]} sur ${it.groupValues[2]}…" }
    Regex("^Paar (\\d+)$").matchEntire(text)?.let { return "Paire ${it.groupValues[1]}" }
    Regex("^Frage (\\d+)$").matchEntire(text)?.let { return "Question ${it.groupValues[1]}" }
    Regex("^Schritt (\\d+)$").matchEntire(text)?.let { return "Étape ${it.groupValues[1]}" }
    Regex("^(\\d+) Paare$").matchEntire(text)?.let { return "${it.groupValues[1]} paires" }
    Regex("^(\\d+) Fragen$").matchEntire(text)?.let { return "${it.groupValues[1]} questions" }
    Regex("^(\\d+) Schritt\\(e\\)$").matchEntire(text)?.let { return "${it.groupValues[1]} étapes" }
    Regex("^(\\d+) Paare · (\\d+) Fragen$").matchEntire(text)?.let { return "${it.groupValues[1]} paires · ${it.groupValues[2]} questions" }
    Regex("^(\\d+) Einträge$").matchEntire(text)?.let { return "${it.groupValues[1]} entrées" }
    Regex("^Fertig: (\\d+) Pakete · (\\d+) Bilder · (.+)$").matchEntire(text)?.let { return "Terminé : ${it.groupValues[1]} packs · ${it.groupValues[2]} images · ${it.groupValues[3]}" }
    Regex("^🎉 (\\d+) Pakete/Ketten & Bilder erfolgreich eingespielt!$").matchEntire(text)?.let { return "🎉 ${it.groupValues[1]} packs/chaînes et images importés avec succès !" }
    Regex("^🎉 '(.+)' angelegt · (\\d+) Paare spielbereit$").matchEntire(text)?.let { return "🎉 '${exactFrench(it.groupValues[1])}' créé · ${it.groupValues[2]} paires prêtes à jouer" }
    Regex("^• ([AB]): (.+) \\(Bild: (.+)\\)$").matchEntire(text)?.let { return "• ${it.groupValues[1]} : ${exactFrench(it.groupValues[2])} (Image : ${it.groupValues[3]})" }
    Regex("^([AB]): (.+)$").matchEntire(text)?.let { return "${it.groupValues[1]} : ${exactFrench(it.groupValues[2])}" }
    Regex("^'(.+)' gelöscht\\.$").matchEntire(text)?.let { return "'${exactFrench(it.groupValues[1])}' supprimé." }
    Regex("^'(.+)' gespeichert\\.$").matchEntire(text)?.let { return "'${exactFrench(it.groupValues[1])}' enregistré." }
    Regex("^Kategorie '(.+)' gespeichert\\.$").matchEntire(text)?.let { return "Catégorie '${exactFrench(it.groupValues[1])}' enregistrée." }
