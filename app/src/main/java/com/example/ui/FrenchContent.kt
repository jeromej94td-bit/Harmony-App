    Regex("^Kette '(.+)' gelöscht\\.$").matchEntire(text)?.let { return "Chaîne '${exactFrench(it.groupValues[1])}' supprimée." }
    Regex("^Bild für '(.+)' gesetzt\\.$").matchEntire(text)?.let { return "Image définie pour '${exactFrench(it.groupValues[1])}'." }
    Regex("^Eigenes Bild für '(.+)' entfernt\\.$").matchEntire(text)?.let { return "Image personnalisée supprimée pour '${exactFrench(it.groupValues[1])}'." }
    Regex("^(.+) „(.+)\\\" an (.+) gesendet$").matchEntire(text)?.let { return "${it.groupValues[1]} a envoyé “${exactFrench(it.groupValues[2])}” à ${it.groupValues[3]}" }
    Regex("^6 Monate im (.+)$").matchEntire(text)?.let { return "6 mois à ${exactFrench(it.groupValues[1])}" }
    Regex("^1 Jahr lang in (.+)$").matchEntire(text)?.let { return "1 an à ${exactFrench(it.groupValues[1])}" }
    Regex("^Weil du (.+) gewählt hast …$").matchEntire(text)?.let { return "Parce que tu as choisi ${exactFrench(it.groupValues[1])}…" }
    Regex("^Verbinde dich mit (.+), um die Antwort zu sehen$").matchEntire(text)?.let { return "Connecte-toi avec ${it.groupValues[1]} pour voir la réponse" }
    Regex("^Verbinde dich mit (.+)$").matchEntire(text)?.let { return "Connecte-toi avec ${it.groupValues[1]}" }
    Regex("^Deine Antworten sind gespeichert\\. Sobald (.+) das Paket beendet, werden beide Antworten gemeinsam sichtbar\\.$").matchEntire(text)?.let { return "Tes réponses sont enregistrées. Lorsque ${it.groupValues[1]} terminera le pack, vous verrez vos deux réponses ensemble." }
    Regex("^Fehler bei der Umformulierung: (.+)$").matchEntire(text)?.let { return "Erreur lors de la reformulation : ${it.groupValues[1]}" }
    Regex("^Fehler bei der Analyse: (.+)$").matchEntire(text)?.let { return "Erreur lors de l'analyse : ${it.groupValues[1]}" }
    Regex("^Fehler bei der Ideengenerierung: (.+)$").matchEntire(text)?.let { return "Erreur lors de la génération d'idées : ${it.groupValues[1]}" }
    if (text.contains(" · ")) {
        val translated = text.split(" · ").joinToString(" · ") { TranslationCatalog.translate(it, AppLanguage.FRENCH) ?: it }
        if (translated != text) return translated
    }
    return null
