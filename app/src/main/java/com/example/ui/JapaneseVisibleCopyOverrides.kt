/** Runtime forms of the interpolated source templates above. */
internal fun localizeJapaneseVisibleCopyDynamic(text: String): String? {
    Regex("^(\\d+) von (\\d+) Bildern im Widget$").matchEntire(text)?.let {
        return "${it.groupValues[1]}枚を選択（ウィジェット内の${it.groupValues[2]}枚中）"
    }
    Regex("^(\\d+) Bilder · auf diesem Gerät bereit$").matchEntire(text)?.let {
        return "${it.groupValues[1]}枚の画像 · この端末で利用可能"
    }
    Regex("^(.+): Verknüpfung folgt später$").matchEntire(text)?.let {
        return "${it.groupValues[1]}：連携は後で利用可能になります"
    }
    Regex("^Deine Antworten sind gespeichert\\. Sobald (.+) das Paket beendet, werden beide Antworten gemeinsam sichtbar\\.$").matchEntire(text)?.let {
        return "あなたの回答は保存されました。${it.groupValues[1]}がこのパックを終えると、二人の回答が一緒に表示されます。"
    }
    Regex("^Frage (\\d+)$").matchEntire(text)?.let {
        return "質問 ${it.groupValues[1]}"
    }
    Regex("^Harmony PicShare · (\\d+) Bilder rotieren$").matchEntire(text)?.let {
        return "Harmony PicShare · ${it.groupValues[1]}枚の画像をローテーション表示"
    }
    Regex("^Verbinde dich mit (.+), um die Antwort zu sehen$").matchEntire(text)?.let {
        return "${it.groupValues[1]}と連携すると回答を表示できます"
    }
    return null
}
